"""Portable blog draft export helpers for CMSBOT output."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from cmsbot.content_ops import resolve_source_dir


def extract_title(html: str) -> str:
    """Extract title from a rendered HTML document."""
    match = re.search(r"<title>(.+?)</title>", html, re.IGNORECASE)
    if match:
        title = match.group(1).strip()
        title = re.sub(r"\s*[|–—-]\s*(CMSBOT|Generated).*$", "", title, flags=re.IGNORECASE)
        if title:
            return title

    match = re.search(r"<h1[^>]*>(.+?)</h1>", html, re.IGNORECASE | re.DOTALL)
    if match:
        return re.sub(r"<[^>]+>", "", match.group(1)).strip()

    return "Untitled Draft"


def extract_meta_description(html: str) -> str:
    """Extract meta description or derive one from the first paragraph."""
    match = re.search(r'<meta\s+name="description"\s+content="([^"]*)"', html, re.IGNORECASE)
    if match:
        return match.group(1).strip()

    match = re.search(r"<p[^>]*>(.+?)</p>", html, re.IGNORECASE | re.DOTALL)
    if match:
        text = re.sub(r"<[^>]+>", "", match.group(1)).strip()
        return text[:200]

    return ""


def extract_body_html(html: str) -> str:
    """Extract the main article HTML content."""
    for tag in ("article", "main"):
        match = re.search(rf"<{tag}[^>]*>(.*?)</{tag}>", html, re.IGNORECASE | re.DOTALL)
        if match:
            return match.group(1).strip()

    match = re.search(r"(<h[12][^>]*>.*)", html, re.IGNORECASE | re.DOTALL)
    if match:
        body = match.group(1)
        body = re.split(r"<footer|<script|Generated by CMSBOT", body, flags=re.IGNORECASE)[0]
        return body.strip()

    return html


def extract_excerpt(body_html: str, max_length: int = 200) -> str:
    """Generate an excerpt from the first non-trivial paragraph."""
    paragraphs = re.findall(r"<p[^>]*>(.+?)</p>", body_html, re.IGNORECASE | re.DOTALL)
    for paragraph in paragraphs:
        text = re.sub(r"<[^>]+>", "", paragraph).strip()
        if len(text) > 40:
            if len(text) <= max_length:
                return text
            truncated = text[:max_length].rsplit(" ", 1)[0]
            return truncated.rstrip(".,;:") + "..."

    return ""


def extract_hero_image(html: str) -> str | None:
    """Extract the hero image from metadata or the first content image."""
    match = re.search(r'<meta\s+property="og:image"\s+content="([^"]*)"', html, re.IGNORECASE)
    if match:
        return match.group(1).strip() or None

    images = re.findall(r'<img[^>]+src="([^"]*)"', html, re.IGNORECASE)
    for image in images:
        if "logo" not in image.lower():
            return image

    return None


def slugify(text: str) -> str:
    """Create a URL-safe slug."""
    slug = text.lower().strip()
    slug = re.sub(r"[^a-z0-9]+", "-", slug)
    slug = slug.strip("-")
    return slug[:80]


def build_blog_draft(
    output_dir: str | Path,
    *,
    category: str | None = None,
    tags: list[str] | None = None,
    author: str | None = None,
    status: str = "draft",
    thumbnail_url: str | None = None,
) -> dict[str, Any]:
    """Build a portable blog draft artifact from CMSBOT output."""
    html_path = Path(output_dir) / "index.html"
    if not html_path.exists():
        raise FileNotFoundError(f"No index.html found in {output_dir}")

    html = html_path.read_text(encoding="utf-8")
    title = extract_title(html)
    body = extract_body_html(html)
    excerpt = extract_excerpt(body)
    meta_description = extract_meta_description(html)
    hero_url = thumbnail_url or extract_hero_image(html)

    body = re.sub(
        r'<[^>]*class="[^"]*footer[^"]*"[^>]*>.*?</[^>]+>',
        "",
        body,
        flags=re.DOTALL | re.IGNORECASE,
    )
    body = re.sub(r"Generated by CMSBOT", "", body, flags=re.IGNORECASE)

    payload = {
        "title": title,
        "slug": slugify(title),
        "content": body,
        "excerpt": excerpt or meta_description[:200] or title,
        "thumbnailUrl": hero_url or "",
        "status": status,
        "author": author,
        "category": category,
        "tags": tags or [],
        "metaDescription": meta_description or excerpt[:160],
    }

    return payload


def export_blog_draft(
    output_dir: str | Path,
    *,
    save_path: str | Path | None = None,
    category: str | None = None,
    tags: list[str] | None = None,
    author: str | None = None,
    status: str = "draft",
    thumbnail_url: str | None = None,
) -> tuple[dict[str, Any], Path]:
    """Write a portable blog draft artifact to disk."""
    output_path = resolve_source_dir(output_dir)
    payload = build_blog_draft(
        output_path,
        category=category,
        tags=tags,
        author=author,
        status=status,
        thumbnail_url=thumbnail_url,
    )
    destination = Path(save_path) if save_path else (output_path / "blog_draft.json")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return payload, destination
